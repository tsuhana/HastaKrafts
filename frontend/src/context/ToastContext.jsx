const ToastContainer = ({ toasts, onRemove }) => {
  if (toasts.length === 0) return null;
  return (
    <div className="hk-toast-container" aria-live="polite">
      {toasts.map(t => (
        <div key={t.id} className={`hk-toast hk-toast--${t.type}`}>
          <span className="hk-toast__icon">{icons[t.type]}</span>
          <span className="hk-toast__msg">{t.message}</span>
          <button className="hk-toast__close" onClick={() => onRemove(t.id)} aria-label="Dismiss">
            {icons.close}
          </button>
        </div>
      ))}
    </div>
  );
};